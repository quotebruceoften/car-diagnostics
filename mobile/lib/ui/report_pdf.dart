import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../core/history.dart';
import '../core/obd/dtc_info.dart';

const _ink = PdfColor.fromInt(0xFF1B2733);
const _muted = PdfColor.fromInt(0xFF5F6B78);
const _line = PdfColor.fromInt(0xFFDDE2E8);
const _accent = PdfColor.fromInt(0xFF1F4E8C);
const _ok = PdfColor.fromInt(0xFF1E8E5A);
const _warn = PdfColor.fromInt(0xFFC77700);
const _bad = PdfColor.fromInt(0xFFC62828);

PdfColor _severityColor(Severity s) => switch (s) {
  Severity.low => _ok,
  Severity.medium => _warn,
  Severity.high || Severity.critical => _bad,
};

String _date(DateTime t) {
  final l = t.toLocal();
  String two(int n) => n.toString().padLeft(2, '0');
  return '${l.year}-${two(l.month)}-${two(l.day)} ${two(l.hour)}:${two(l.minute)}';
}

/// A shareable A4 report of [record], with changes since [previous] if given.
Future<Uint8List> buildScanReport(ScanRecord record, {ScanRecord? previous}) {
  final doc = pw.Document(title: 'Scan report ${record.carName}', author: 'Car Diagnostics');
  final withFaults = record.modules.where((m) => m.faults.isNotEmpty).toList();
  final clean = record.modules.where((m) => m.faults.isEmpty && m.faultsReadable).toList();
  final comparison = previous == null ? null : ScanComparison(record, previous);

  pw.Widget label(String text) => pw.Padding(
    padding: const pw.EdgeInsets.only(top: 18, bottom: 6),
    child: pw.Text(
      text.toUpperCase(),
      style: pw.TextStyle(fontSize: 9, color: _accent, fontWeight: pw.FontWeight.bold, letterSpacing: 1.2),
    ),
  );

  pw.Widget stat(String value, String caption, PdfColor color) => pw.Expanded(
    child: pw.Container(
      padding: const pw.EdgeInsets.all(12),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: _line),
        borderRadius: pw.BorderRadius.circular(8),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            value,
            style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold, color: color),
          ),
          pw.SizedBox(height: 2),
          pw.Text(caption, style: const pw.TextStyle(fontSize: 9, color: _muted)),
        ],
      ),
    ),
  );

  pw.Widget fault(FaultRecord f, {PdfColor? colorOverride}) {
    final info = dtcInfo(f.code);
    final color = colorOverride ?? _severityColor(info.severity);
    return pw.Container(
      padding: const pw.EdgeInsets.symmetric(vertical: 6),
      decoration: const pw.BoxDecoration(
        border: pw.Border(bottom: pw.BorderSide(color: _line, width: 0.5)),
      ),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.SizedBox(
            width: 70,
            child: pw.Text(
              f.display,
              style: pw.TextStyle(fontWeight: pw.FontWeight.bold, color: color),
            ),
          ),
          pw.Expanded(
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(info.isGeneric ? f.description : info.title, style: const pw.TextStyle(color: _ink)),
                pw.Text(
                  '${info.severity.label}: ${info.severity.advice}'
                  '${f.active == null ? '' : (f.active! ? ' - active now' : ' - stored')}',
                  style: const pw.TextStyle(fontSize: 9, color: _muted),
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }

  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.fromLTRB(40, 40, 40, 32),
      theme: pw.ThemeData.withFont(),
      footer: (context) => pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text('Generated by Car Diagnostics', style: const pw.TextStyle(fontSize: 8, color: _muted)),
          pw.Text(
            'Page ${context.pageNumber} of ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 8, color: _muted),
          ),
        ],
      ),
      build: (context) => [
        pw.Text('Vehicle scan report', style: const pw.TextStyle(fontSize: 10, color: _accent)),
        pw.SizedBox(height: 4),
        pw.Text(
          record.carName,
          style: pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold, color: _ink),
        ),
        pw.SizedBox(height: 4),
        pw.Text(
          '${record.vin.isEmpty ? 'VIN not reported' : 'VIN ${record.vin}'}   |   Scanned ${_date(record.timestamp)}'
          '${previous == null ? '' : '   |   Compared with ${_date(previous.timestamp)}'}',
          style: const pw.TextStyle(fontSize: 10, color: _muted),
        ),
        pw.SizedBox(height: 16),
        pw.Row(
          children: [
            stat('${record.modules.length}', 'modules answered', _ink),
            pw.SizedBox(width: 10),
            stat('${record.faultCount}', 'fault codes', record.faultCount == 0 ? _ok : _bad),
            if (comparison != null) ...[
              pw.SizedBox(width: 10),
              stat('${comparison.added.length}', 'new since last scan', comparison.added.isEmpty ? _ok : _bad),
              pw.SizedBox(width: 10),
              stat('${comparison.fixed.length}', 'gone since last scan', _ok),
            ],
          ],
        ),
        if (withFaults.isNotEmpty) label('Fault codes'),
        for (final m in withFaults) ...[
          pw.Padding(
            padding: const pw.EdgeInsets.only(top: 8, bottom: 2),
            child: pw.Text(
              '${m.label}${m.partNumber.isEmpty ? '' : '   (${m.partNumber})'}',
              style: pw.TextStyle(fontWeight: pw.FontWeight.bold, color: _ink),
            ),
          ),
          for (final f in m.faults) fault(f),
        ],
        if (comparison != null && comparison.fixed.isNotEmpty) ...[
          label('No longer present since the previous scan'),
          for (final (module, f) in comparison.fixed)
            pw.Text('$module: ${f.display} ${f.description}', style: const pw.TextStyle(fontSize: 10, color: _muted)),
        ],
        if (clean.isNotEmpty) ...[
          label('Modules without faults'),
          pw.Wrap(
            spacing: 6,
            runSpacing: 6,
            children: [
              for (final m in clean)
                pw.Container(
                  padding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                  decoration: pw.BoxDecoration(
                    border: pw.Border.all(color: _line),
                    borderRadius: pw.BorderRadius.circular(10),
                  ),
                  child: pw.Text(m.label, style: const pw.TextStyle(fontSize: 9, color: _ink)),
                ),
            ],
          ),
        ],
        pw.SizedBox(height: 24),
        pw.Text(
          'Severity ratings and explanations are general guidance, not a diagnosis. The same code can have '
          'different causes on different engines.',
          style: const pw.TextStyle(fontSize: 8, color: _muted),
        ),
      ],
    ),
  );
  return doc.save();
}
